def main() -> None:
    """Write every demo scan and its fixture, then drop fixtures of previous outputs."""
    SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    fixture_names: set[str] = set()
    for scan in DEMO_SCANS:
        path = SAMPLES_DIR / scan.file_name
        save_scan(scan, path)
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        fixture = FIXTURES_DIR / f"{digest}.json"
        fixture.write_text(render_fixture(scan), encoding="utf-8")
        fixture_names.add(fixture.name)
        print(f"{path.relative_to(ROOT)}  sha256={digest}")
    for stale in FIXTURES_DIR.iterdir():
        if _HASH_FIXTURE.fullmatch(stale.name) and stale.name not in fixture_names:
            stale.unlink()
            print(f"removed stale fixture {stale.relative_to(ROOT)}")


def save_scan(scan: DemoScan, path: Path) -> None:
    """Draw the blank pages and save them in the format implied by the file extension."""
    pages = [
        draw_page(scan, rows, page_number, len(scan.pages))
        for page_number, rows in enumerate(scan.pages, start=1)
    ]
    match path.suffix:
        case ".pdf":
            pages[0].save(path, "PDF", resolution=DPI, save_all=True, append_images=pages[1:])
        case ".jpg":
            pages[0].save(path, "JPEG", quality=88, dpi=(DPI, DPI))
        case ".png":
            pages[0].save(path, "PNG", dpi=(DPI, DPI))
        case _:
            raise ValueError(f"unsupported demo scan format: {path.name}")


def draw_page(
    scan: DemoScan, rows: tuple[BlankRow, ...], page_number: int, page_count: int
) -> Image.Image:
    """Draw one A4 blank page with the header, the results table and the demo mark."""
    page = Image.new("RGB", PAGE_SIZE, "white")
    _draw_watermark(page)
    draw = ImageDraw.Draw(page)
    title_font = ImageFont.truetype(BOLD_FONT, 44)
    bold_font = ImageFont.truetype(BOLD_FONT, 26)
    text_font = ImageFont.truetype(REGULAR_FONT, 26)
    small_font = ImageFont.truetype(REGULAR_FONT, 20)

    draw.text((MARGIN, 80), "ДЕМО-ЛАБОРАТОРИЯ", font=title_font, fill=INK)
    draw.text(
        (MARGIN, 140),
        "Вымышленный бланк для демонстрации прототипа. Не медицинский документ.",
        font=small_font,
        fill=INK,
    )
    draw.line((MARGIN, 180, PAGE_SIZE[0] - MARGIN, 180), fill=INK, width=3)
    header_lines = (
        f"Пациент: {scan.patient_name}",
        f"Исследование: {scan.study}",
        f"Дата забора: {scan.collected_at}",
    )
    for line_number, line in enumerate(header_lines):
        draw.text((MARGIN, 205 + line_number * 42), line, font=text_font, fill=INK)

    table_top = 360
    for x, caption in zip(COLUMN_X, ("Показатель", "Результат", "Ед.", "Норма"), strict=True):
        draw.text((x + 8, table_top + 14), caption, font=bold_font, fill=INK)
    for row_number, row in enumerate(rows, start=1):
        y = table_top + row_number * ROW_HEIGHT + 14
        value_ink = INK if row.confidence >= 0.8 else FADED_INK
        draw.text((COLUMN_X[0] + 8, y), row.name, font=text_font, fill=INK)
        draw.text((COLUMN_X[1] + 8, y), row.value_raw, font=bold_font, fill=value_ink)
        draw.text((COLUMN_X[2] + 8, y), row.unit, font=text_font, fill=INK)
        draw.text((COLUMN_X[3] + 8, y), row.ref_range, font=text_font, fill=INK)
    table_bottom = table_top + (len(rows) + 1) * ROW_HEIGHT
    for line_number in range(len(rows) + 2):
        y = table_top + line_number * ROW_HEIGHT
        draw.line((MARGIN, y, PAGE_SIZE[0] - MARGIN, y), fill=GRID, width=2)
    for x in (*COLUMN_X, PAGE_SIZE[0] - MARGIN):
        draw.line((x, table_top, x, table_bottom), fill=GRID, width=2)

    footer = f"ДЕМО · только вымышленные данные · стр. {page_number} из {page_count}"
    draw.text((MARGIN, PAGE_SIZE[1] - 110), footer, font=small_font, fill=INK)
    return page


def _draw_watermark(page: Image.Image) -> None:
    mark = Image.new("L", (1400, 360), 0)
    ImageDraw.Draw(mark).text((40, 20), "ДЕМО", font=ImageFont.truetype(BOLD_FONT, 300), fill=255)
    mark = mark.rotate(35, expand=True)
    offset = ((PAGE_SIZE[0] - mark.width) // 2, (PAGE_SIZE[1] - mark.height) // 2 + 200)
    page.paste(Image.new("RGB", mark.size, WATERMARK), offset, mark)


def render_fixture(scan: DemoScan) -> str:
    """Return the extraction answer for the scan as the FakeExtractor fixture JSON."""
    items = [
        ExtractedItem(
            test_name_raw=row.name,
            value=float(row.value_raw.replace(",", ".")),
            value_raw=row.value_raw,
            unit=row.unit,
            ref_range=row.ref_range,
            flag=row.flag,
            confidence=row.confidence,
            needs_review=row.confidence < 0.8,
        )
        for rows in scan.pages
        for row in rows
    ]
    result = ExtractionResult(items=items)
    return json.dumps(result.model_dump(mode="json"), ensure_ascii=False, indent=2) + "\n"


